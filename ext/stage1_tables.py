"""Stage 1 result tables, recomputed from the raw run records in ext/runs/ (no numbers typed by hand).
usage: python -I ext/stage1_tables.py  ->  ext/runs/STAGE1_TABLES.md"""
import os, sys, json, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); RUNS = os.path.join(HERE, 'runs'); sys.path.insert(0, HERE)
import stage1_stats as ST
L = []; P = L.append
def J(n):
    p = os.path.join(RUNS, n); return json.load(open(p)) if os.path.exists(p) else None
def g(r, d=2): return f"{r['G']:.{d}f} [{r['lo']:.{d}f}, {r['hi']:.{d}f}]"
def gm(e): return float(np.exp(np.mean(np.log(e))))
OAk = ['OA-VCB init0', 'OA-VCB init1', 'OA-VCB init2']
P('# Stage 1 result tables (generated by `ext/stage1_tables.py` from `ext/runs/*.json`)\n')
P('G(X → Y) = exp(mean log(e_X / e_Y)), the paired geometric gain of Y over X; [pointwise 95% bootstrap over operators, 10 000 resamples]. W = fraction of samples where Y is more accurate.\n')
# ---------------- confirmatory
P('## 1 Confirmatory: P1–P3 on set C\n')
for fam in ('channels', 'barriers'):
    d = J(f'confirm_C_{fam}.json'); c = d['confirmatory']
    P(f'### {fam} (n = {len(d["data"]["ids"])}, rng {d["data"]["rng_seed"]}; gates: {"all passed" if all(v["passed"] for v in d["gates"].values()) else "FAILED"})\n')
    P('| | P1: R = G(PCG → OA-VCB) | W | band | P1 guarded | P2: G(POLY-S → OA-VCB) | W |'); P('|---|---|---|---|---|---|---|')
    for k in OAk:
        x = c[k]; P(f"| {k} | {g(x['P1'], 3)} | {x['P1']['W']:.2f} | {x['P1']['band']} | {g(x['P1_guarded'], 3)} | {g(x['P2'], 3)} | {x['P2']['W']:.2f} |")
    P(f"\n**P3** = G(CHEB-legacy → PCG) = {g(c['P3'], 3)}, W = {c['P3']['W']:.2f} (guarded identical: {c['P3_guarded']['G'] == c['P3']['G']}).  **P1 family label: {c['P1_family_label']}.**")
    fl = {m: f['nonfinite_or_crash'] for m, f in d['failures'].items() if f['nonfinite_or_crash']}
    st = {m: f['status_counts'] for m, f in d['failures'].items() if f['status_counts']}
    P(f"Failures (non-finite/crash): {fl or 'none'}; other status counts: {st or 'none'}.\n")
# ---------------- secondary on C
P('## 2 Secondary on set C: every one-pass method against OA-VCB\n')
for fam in ('channels', 'barriers'):
    d = J(f'confirm_C_{fam}.json'); E = d['errors']; s = d['secondary']; ph = d['recovered_log_gain']
    P(f"### {fam} (champion {d['preconfirmation']['champion']}; spatial controls {d['preconfirmation']['spatial']})\n")
    P('| Method X | geo-mean error | G(CHEB-legacy → X) | matvec/pass | G(X → OA-VCB) init 0 | init 1 | init 2 | φ_X (init 0) |'); P('|---|---|---|---|---|---|---|---|')
    for m in ['CHEB-legacy', 'CHEB', 'CHEB-T', 'POLY-S', 'POLY-L', 'SD', 'MR', 'PCG', 'K2 (CHEB)'] + d['preconfirmation']['spatial']:
        base = '1.00' if m == 'CHEB-legacy' else g(s[f'CHEB-legacy -> {m}'])
        p = ph.get(f'{m} | OA-VCB init0'); pp = f"{p['phi']:.2f} [{p['lo']:.2f}, {p['hi']:.2f}]" + (' (unstable)' if p['unstable'] else '') if p else '–'
        P(f"| {m} | {gm(E[m]):.3e} | {base} | {('%.0f' % d['matvecs_per_pass'][m]) if m in d['matvecs_per_pass'] else '30 (not counted)'} | " + ' | '.join(g(s[f'{m} -> {k}']) for k in OAk) + f" | {pp} |")
    for m in [k for k in E if k.startswith('OA-')]:
        P(f"| *{m}* | {gm(E[m]):.3e} | {g(s[f'CHEB-legacy -> {m}'])} | – | – | – | – | – |")
    P('')
# ---------------- subgroups C barriers + set S
P('## 3 Structure subgroups (barriers)\n')
for nm, fn in (('set C', 'confirm_C_barriers.json'), ('set S (stratified, 20 per category)', 'confirm_S_barriers.json')):
    d = J(fn)
    if d is None: continue
    if d['data'].get('set_S'): P(f"{nm}: {d['data']['set_S']}\n")
    champ = d['preconfirmation']['champion']
    P(f'**{nm}**, OA-VCB init 0\n'); P('| category | n | G(CHEB-legacy → OA-VCB) | G(PCG → OA-VCB) | G(POLY-S → OA-VCB) | G(K2 → OA-VCB) | G(SGS → OA-VCB) | G(SGS-PCG → OA-VCB) |'); P('|---|---|---|---|---|---|---|---|')
    for cat, v in d['subgroups'].items():
        if not v['gains']: P(f"| {cat} | {v['n']} | (n < 3) | | | | | |"); continue
        gg = v['gains']
        P(f"| {cat} | {v['n']} | " + ' | '.join(g(gg[f'{x} -> OA-VCB init0']) for x in ('CHEB-legacy', 'PCG', 'POLY-S', 'K2 (CHEB)', 'SGS', 'SGS-PCG')) + ' |')
    P('')
# ---------------- LC
d = J('confirm_LC_channels.json')
if d:
    P('## 4 Load challenge (set LC; 50 channel operators of C × 4 loads)\n')
    models = [k for k in d['errors'] if k.startswith('OA-VCB')]
    P('| load | n | G(PCG → model): ' + ' | '.join(models) + ' | G(SGS-PCG → model): ' + ' | '.join(models) + ' |'); P('|---|---|' + '---|' * (2 * len(models)))
    for ld, v in d['subgroups'].items():
        gg = v['gains']; P(f"| {ld} | {v['n']} | " + ' | '.join(g(gg[f'PCG -> {m}']) for m in models) + ' | ' + ' | '.join(g(gg[f'SGS-PCG -> {m}']) for m in models) + ' |')
    s = d['secondary']; P('| pooled (operator bootstrap) | 200 | ' + ' | '.join(g(s[f'PCG -> {m}']) for m in models) + ' | ' + ' | '.join(g(s[f'SGS-PCG -> {m}']) for m in models) + ' |')
    P('\n| load | ' + ' | '.join(['PCG', 'SGS-PCG'] + models) + ' |  (geometric-mean relative energy error)'); P('|---|' + '---|' * (2 + len(models)))
    for ld, v in d['subgroups'].items():
        k = [j for j, l in enumerate(d['data']['loads']) if l == ld]
        P(f'| {ld} | ' + ' | '.join(f"{gm(np.array(d['errors'][m])[k]):.2e}" for m in ['PCG', 'SGS-PCG'] + models) + ' |')
    P('')
# ---------------- R
P('## 5 Retrospective seeds (set R; previously inspected data)\n'); P('| set | family | model | P1-type R = G(PCG → model) | band | G(POLY-S → model) | G(SGS-PCG → model) | P3 |'); P('|---|---|---|---|---|---|---|---|')
for st_ in ('R2', 'R3'):
    for fam in ('channels', 'barriers'):
        d = J(f'confirm_{st_}_{fam}.json')
        if not d: continue
        c = d['primary_comparisons_dry_run']
        for m in [k for k in d['errors'] if k.startswith('OA-VCB')]:
            P(f"| {st_} | {fam} | {m} | {g(c[m]['P1'], 3)} | {c[m]['P1']['band']} | {g(c[m]['P2'], 3)} | {g(d['secondary'][f'SGS-PCG -> {m}'])} | {g(c['P3'], 3)} |")
P('')
# ---------------- D1
P('## 6 D1 on set C (OA-VCB init 0, fine level; ρ = E_NN / E_K4)\n'); P('| family | position | ρ quantiles 10/50/90% | δ median | ranks | local separation (rank 4, ρ ≤ 0.99) | max |E_PCG/E_K − 1| |'); P('|---|---|---|---|---|---|---|')
for fam in ('channels', 'barriers'):
    d = J(f'd1_C_{fam}.json')
    if not d: continue
    for k, v in d['summary'].items():
        P(f"| {fam} | {k} | {' / '.join(f'{q:.3f}' for q in v['rho_q'])} | {v['delta_median']:.3f} | {v['ranks']} | {v['n_local_separation']}/{len(d['records'])} | {v['pcg_vs_K_max']:.1e} |")
P('')
# ---------------- D2
P('## 7 D2 on set C (per-operator oracle-fitted polynomial candidate)\n')
for fam in ('channels', 'barriers'):
    d2 = J(f'd2_C_{fam}.json'); d = J(f'confirm_C_{fam}.json')
    if not d2: P(f'{fam}: not yet available.\n'); continue
    assert d2['ids'] == d['data']['ids']; e = d2['errors_D2']
    P(f"**{fam}**: geo-mean error {gm(e):.3e}; kept starts { {s_: d2['kept_start'].count(s_) for s_ in sorted(set(d2['kept_start']))} }; gates {'passed' if all(v['passed'] for v in d2['gates'].values()) else 'FAILED'}; "
      f"stops per start { {k: {s_: v['stop'].count(s_) for s_ in sorted(set(v['stop']))} for k, v in d2['starts'].items()} }\n")
    P('| comparison | G | W |'); P('|---|---|---|')
    for x, y in [('PCG', 'D2'), ('POLY-L', 'D2'), ('SGS-PCG', 'D2')] + [('D2', k) for k in OAk]:
        ex = e if x == 'D2' else d['errors'][x]; ey = e if y == 'D2' else d['errors'][y]; r = ST.paired(ex, ey)
        P(f'| {x} → {y} | {g(r)} | {r["W"]:.2f} |')
    if fam == 'barriers':
        lab = [l['category'] for l in d['labels']]
        for cat in sorted(set(lab)):
            k = [j for j, l in enumerate(lab) if l == cat]
            if len(k) >= 3: r = ST.paired(np.array(e)[k], np.array(d['errors']['OA-VCB init0'])[k]); P(f'| D2 → OA-VCB init0, {cat} (n = {len(k)}) | {g(r)} | {r["W"]:.2f} |')
    P('')
# ---------------- timing
P('## 8 Timing on set C (first 50 operators per family; per-operator latency, median of 5 repeats; 2 threads)\n')
for fam in ('channels', 'barriers'):
    T = J(f'timing_C_{fam}.json')
    if not T: continue
    recs = T['records']; oa = np.array([r['errors']['1pass OA-VCB batch1'] for r in recs])
    P(f"**{fam}** — CPU {T['env']['cpu']}\n"); P('| method | latency median [ms] | geo-mean error |'); P('|---|---|---|')
    for k in recs[0]['raw_seconds']:
        if k.startswith('curve'): continue
        med = np.median([np.median(r['raw_seconds'][k]) for r in recs]) * 1e3
        e = '' if k == 'direct' else f"{gm([r['errors'][k] for r in recs]):.3e}"
        P(f'| {k} | {med:.1f} | {e} |')
    od = np.median([np.median(r['oavcb_operator_data_seconds']) for r in recs]) * 1e3
    P(f"\nOA-VCB batch-1 latency includes operator data {od:.0f} ms. Offline time to reach OA-VCB's per-sample error (oracle stopping, median; censored = not reached):\n")
    P('| solver | time [ms] | iterations | censored |'); P('|---|---|---|---|')
    for k in recs[0]['raw_seconds']:
        if not k.startswith('curve'): continue
        tt, it, cens = [], [], 0
        for r, eo in zip(recs, oa):
            h = r['errors'][k]; hit = next((i for i, v in enumerate(h) if v <= eo), None)
            if hit is None: cens += 1; continue
            tt.append(np.median([s[hit] for s in r['curve_stamps'][k]])); it.append(hit + 1)
        P(f"| {k[6:]} | {1e3 * np.median(tt):.1f} | {np.median(it):.0f} | {cens}/{len(recs)} |")
    P('\nThroughput (secondary): ' + ', '.join(f'{k} {1e3 * v:.0f} ms' for k, v in T['throughput'].items()) + '\n')
open(os.path.join(RUNS, 'STAGE1_TABLES.md'), 'w').write('\n'.join(L)); print('\n'.join(L))
