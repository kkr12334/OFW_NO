"""Route C pilot analysis, fixed before any pilot geometry is generated (ROUTE_C_PILOT_AMENDMENT_1 section 6-9).

    python3 rc_pilot_analysis.py [pilot|smoke]      -> pilot_analysis.json, pilot_tables.md   (smoke: code-path test only)

Definitions (amendment section 6):
  W(op)   largest energy effectivity over the four problems and the six common inputs, resolved cases only
  lam(op) largest eta_m / eta_M6 over the same cases
  E1      median over operators of W (max reported);  E2 = E1(1e4) / E1(1);  E3 median and p90 (numpy linear) of lam, max reported
  Candidate quality (M3, per family): Support / Stop / Inconclusive;  adaptation Q = E1(M1SZ, 1e4) / E1(M3, 1e4)
"""
import os, sys, json, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
MODE = sys.argv[1] if len(sys.argv) > 1 else 'pilot'
COMMON = ['coarse', 'pcg10', 'pcg30', 'pcg100', 'noise10', 'smooth10']
PRIMARY = [1.0, 1e2, 1e4]
med = lambda x: float(np.median(x)) if len(x) else float('nan')
p90 = lambda x: float(np.percentile(x, 90)) if len(x) else float('nan')
mx = lambda x: float(np.max(x)) if len(x) else float('nan')


def load(fam, lev):
    p = os.path.join(HERE, 'runs', f'{MODE}_{fam}_L{lev}.json')
    return json.load(open(p)) if os.path.exists(p) else None


def cases(op, m, inputs=COMMON):
    return [(p, i) for p in op['norms'] for i in inputs if f'{p}|{i}' in op['resolved'] and op['resolved'][f'{p}|{i}'] and f'{p}|{i}|{m}' in op['eta']]


def W(op, m, inputs=COMMON):
    c = cases(op, m, inputs)
    return max(op['eta'][f'{p}|{i}|{m}'] / op['err'][f'{p}|{i}'] for p, i in c) if c else float('nan')


def lam(op, m):
    c = cases(op, m)
    return max(op['eta'][f'{p}|{i}|{m}'] / op['eta'][f'{p}|{i}|M6'] for p, i in c) if c else float('nan')


def by_contrast(d):
    out = {}
    for op in d['operators']:
        if op.get('status') == 'complete': out.setdefault(op['contrast'], []).append(op)
    return out


res = dict(mode=MODE, families={})
md = [f'# Route C pilot tables ({MODE})\n', 'Generated by `rc_pilot_analysis.py` from the raw run records. Definitions: amendment §6.\n']
for fam in ('channels', 'barriers'):
    d = load(fam, 3)
    if d is None: continue
    R = dict(status=d['status'], gates=len(d['gates']), gates_all_passed=all(g['passed'] for g in d['gates']), peak_rss_gb=d.get('peak_rss_gb'))
    methods = d['design']['methods']; bc = by_contrast(d); contrasts = sorted(bc)
    R['n_operators'] = {str(c): len(v) for c, v in bc.items()}
    # per-operator values
    per = {m: {str(c): dict(ids=[o['id'] for o in bc[c]], W=[W(o, m) for o in bc[c]], lam=[lam(o, m) for o in bc[c]],
                            W_oavcb=[W(o, m, ['oavcb']) if any(k.startswith('primal|oavcb') for k in o['err']) else None for o in bc[c]])
               for c in contrasts} for m in methods}
    R['per_operator'] = per
    E1 = {m: {str(c): dict(median=med(per[m][str(c)]['W']), max=mx(per[m][str(c)]['W'])) for c in contrasts} for m in methods}
    E3 = {m: {str(c): dict(median=med(per[m][str(c)]['lam']), p90=p90(per[m][str(c)]['lam']), max=mx(per[m][str(c)]['lam'])) for c in contrasts} for m in methods}
    E2 = {m: (E1[m]['10000.0']['median'] / E1[m]['1.0']['median']) if ('10000.0' in E1[m] and '1.0' in E1[m]) else float('nan') for m in methods}
    R.update(E1=E1, E2=E2, E3=E3)
    # per-input breakdown: median over operators of the max over problems
    R['by_input'] = {m: {str(c): {i: med([W(o, m, [i]) for o in bc[c]]) for i in COMMON} for c in contrasts} for m in methods}
    # candidate quality (M3)
    prim = [c for c in PRIMARY if c in bc]
    if len(prim) == len(PRIMARY):
        e1ok = all(E1['M3'][str(c)]['median'] <= 1.5 for c in prim)
        e3ok = all(E3['M3'][str(c)]['median'] <= 1.10 and E3['M3'][str(c)]['p90'] <= 1.5 for c in prim)
        stop = E2['M3'] > 2 or any(E3['M3'][str(c)]['median'] > 1.5 for c in prim) or not R['gates_all_passed'] or d['status'] != 'complete'
        support = (not stop) and e1ok and E2['M3'] <= 1.25 and e3ok
        R['candidate'] = dict(classification='Stop' if stop else ('Support' if support else 'Inconclusive'),
                              E1_le_1p5_all=e1ok, E2=E2['M3'], E3_ok_all=e3ok)
    else:
        R['candidate'] = dict(classification='n/a (not all primary contrasts present)')
    # adaptation effect (matched) and the superseded unmatched rule
    Q = {str(c): E1['M1SZ'][str(c)]['median'] / E1['M3'][str(c)]['median'] for c in contrasts}
    q4 = Q.get('10000.0', float('nan'))
    R['adaptation'] = dict(Q=Q, classification=('benefit' if q4 >= 1.5 else ('no benefit' if q4 <= 1.10 else 'inconclusive')),
                           n_ops_M1SZ_ge_1p5_M3={str(c): int(sum(a >= 1.5 * b for a, b in zip(per['M1SZ'][str(c)]['W'], per['M3'][str(c)]['W']))) for c in contrasts},
                           superseded_unmatched_rule=dict(M1_ratio=E1['M1']['10000.0']['median'] / E1['M3']['10000.0']['median'] if '10000.0' in E1['M1'] else None,
                                                          M2_ratio=E1['M2']['10000.0']['median'] / E1['M3']['10000.0']['median'] if '10000.0' in E1['M2'] else None))
    nk = {str(c): [o['near_kernel'] for o in bc[c]] for c in contrasts}
    R['near_kernel'] = dict(dims=nk, informative=any(v >= 1 for c in nk for v in nk[c]),
                            M4_over_M3={str(c): E1['M4'][str(c)]['median'] / E1['M3'][str(c)]['median'] for c in contrasts},
                            M1S_over_M1SZ={str(c): E1['M1S'][str(c)]['median'] / E1['M1SZ'][str(c)]['median'] for c in contrasts})
    R['lifting'] = {str(c): E1['M5'][str(c)]['median'] / E1['M3'][str(c)]['median'] for c in contrasts}
    R['classical_separation'] = {m: dict(E2=E2[m], separation=bool(E2[m] >= 3)) for m in ('M0', 'M0p')}
    # goal metrics (descriptive): over operators x goals x pairs
    G = {}
    for c in contrasts:
        for m in methods:
            rows = [g for o in bc[c] for g in o['goals'] if g['method'] == m and g['primal'] != 'exact']
            res_rows = [g for g in rows if g['eu'] > 0 and g['ez'] > 0]
            for pair in sorted({g['primal'] for g in rows}):
                rr = [g for g in res_rows if g['primal'] == pair]
                if not rr: continue
                pe = [g['product_radius'] / (g['eu'] * g['ez']) for g in rr]
                rel_p = [g['product_radius'] / abs(g['Jh']) for g in rr]
                rel_q = [0.5 * (g['polar_hi'] - g['polar_lo']) / abs(g['Jh']) for g in rr]
                cg = [g['product_radius'] / abs(g['rem']) for g in rr if abs(g['rem']) > 1e-12 * (abs(g['Jh']) + abs(g['centre']))]
                G.setdefault(m, {}).setdefault(str(c), {})[pair] = dict(product_efficiency_median=med(pe), product_efficiency_max=mx(pe),
                    rel_radius_product_median=med(rel_p), rel_radius_polar_median=med(rel_q), rel_radius_polar_max=mx(rel_q),
                    corrected_goal_effectivity_median=med(cg), n=len(rr))
    R['goals'] = G
    # stopping
    ST = {}
    for c in contrasts:
        for m in d['design']['stop_methods']:
            for key in bc[c][0]['stop'][m]['attainment']:
                fc = [o['stop'][m]['attainment'][key]['first_check'] for o in bc[c]]
                tr = [o['stop'][m]['attainment'][key]['trigger'] for o in bc[c]]
                att = [x for x in fc if x is not None]
                ST.setdefault(str(c), {}).setdefault(m, {})[key] = dict(fraction_attained=len(att) / len(fc), median_first_check=med(att) if att else None,
                                                                        per_operator=fc, triggers=tr)
    R['stopping'] = ST
    # indices and C_glob
    R['indices'] = {str(c): {pu: dict(max_median=med([o['diag'][pu]['floating_max'] for o in bc[c]]), max_max=mx([o['diag'][pu]['floating_max'] for o in bc[c]]),
                                      p95_median=med([o['diag'][pu]['floating_p95'] for o in bc[c]]),
                                      worst=[dict(id=o['id'], **o['diag'][pu]['worst3'][0]) for o in bc[c]])
                             for pu in ('G1', 'G1SZ', 'OAZ')} for c in contrasts}
    R['C_glob'] = {str(c): [dict(id=o['id'], C_glob=o['diag']['C_glob']) for o in bc[c] if 'C_glob' in o['diag']] for c in contrasts}
    R['work_median'] = {m: {k: med([o['work'][m][k] for c in contrasts for o in bc[c]]) for k in
                            ('patches', 'flux_unknowns', 'constraints', 'patch_elements', 'lu_nnz', 'max_patch_elements', 'coarse_dim')
                            if k in bc[contrasts[0]][0]['work'][m]} for m in methods}
    # L4 arm
    d4 = load(fam, 4)
    if d4 is not None:
        b4 = by_contrast(d4); L4 = dict(status=d4['status'], gates=len(d4['gates']), gates_all_passed=all(g['passed'] for g in d4['gates']), rows=[])
        for c, ops in b4.items():
            for o4 in ops:
                o3 = [o for o in bc.get(c, []) if o['id'] == o4['id']]
                for m in d4['design']['methods']:
                    L4['rows'].append(dict(id=o4['id'], contrast=c, method=m, W_L4=W(o4, m), W_L3=W(o3[0], m) if o3 else None,
                                           ratio=(W(o4, m) / W(o3[0], m)) if o3 else None))
        L4['M3_max_ratio'] = mx([r['ratio'] for r in L4['rows'] if r['method'] == 'M3' and r['ratio'] is not None])
        L4['M3_no_gross_deterioration'] = bool(L4['M3_max_ratio'] <= 1.25)
        R['L4'] = L4
    res['families'][fam] = R
    # ---------------------------------------------------------------- markdown tables
    md.append(f'\n## {fam}\n\nStatus: {d["status"]}; {R["gates"]} gates, all passed: {R["gates_all_passed"]}. Operators per contrast: {R["n_operators"]}.\n')
    md.append('\n**E1 (median [max] over operators of W):**\n\n| Method | ' + ' | '.join(f'c = {c:g}' for c in contrasts) + ' | E2 |\n|---|' + '---:|' * (len(contrasts) + 1))
    for m in methods:
        md.append(f'| {m} | ' + ' | '.join(f"{E1[m][str(c)]['median']:.2f} [{E1[m][str(c)]['max']:.2f}]" for c in contrasts) + f' | {E2[m]:.2f} |')
    md.append('\n**E3 (median / p90 [max] of η_m / η_M6):**\n\n| Method | ' + ' | '.join(f'c = {c:g}' for c in contrasts) + ' |\n|---|' + '---:|' * len(contrasts))
    for m in methods:
        md.append(f'| {m} | ' + ' | '.join(f"{E3[m][str(c)]['median']:.3f} / {E3[m][str(c)]['p90']:.3f} [{E3[m][str(c)]['max']:.3f}]" for c in contrasts) + ' |')
    md.append(f"\n**Candidate (M3):** {R['candidate']}\n\n**Adaptation:** {R['adaptation']}\n\n**Near-kernel:** {R['near_kernel']}\n\n"
              f"**Lifting (E1 M5/M3):** {R['lifting']}\n\n**Classical separation:** {R['classical_separation']}\n")
json.dump(res, open(os.path.join(HERE, f'{MODE}_analysis.json' if MODE != 'pilot' else 'pilot_analysis.json'), 'w'), indent=1, default=float)
open(os.path.join(HERE, f'{MODE}_tables.md' if MODE != 'pilot' else 'pilot_tables.md'), 'w').write('\n'.join(md) + '\n')
print('\n'.join(md))
